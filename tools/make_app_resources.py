"""Writes the resource script for bin/vitro.exe and the table that tells the program what is inside it.

vitro.exe is one file. It carries, as RCDATA resources:
  * the web app (every file under web/dist, served to the window at /<path>),
  * the sample traces of samples/ (listed in the library),
  * WebView2Loader.dll from the SDK that tools/fetch_webview2.py unpacked,
  * THIRD_PARTY_NOTICES.txt,
plus the icon, the manifest and the version information. Resource 1 is a table of the others, one line per item:
    <id> TAB <kind> TAB <mime> TAB <name>
(see cpp/src/app_assets.hpp).

    python tools/make_app_resources.py --out bin/_obj/app
writes bin/_obj/app/vitro_app.rc and bin/_obj/app/table.txt, which build.sh hands to windres.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

MIME = {
    '.html': 'text/html; charset=utf-8',
    '.js': 'text/javascript; charset=utf-8',
    '.css': 'text/css; charset=utf-8',
    '.svg': 'image/svg+xml',
    '.woff2': 'font/woff2',
    '.png': 'image/png',
    '.ico': 'image/x-icon',
}
SAMPLE_SUFFIXES = ('.vtdump', '.vtdemo')


def project_version() -> tuple[str, tuple[int, int, int]]:
    with open(os.path.join(ROOT, 'pyproject.toml'), encoding='utf-8') as fh:
        m = re.search(r'^version\s*=\s*"(\d+)\.(\d+)\.(\d+)"', fh.read(), re.MULTILINE)
    if m is None:
        raise RuntimeError('pyproject.toml has no version = "X.Y.Z"')
    nums = (int(m.group(1)), int(m.group(2)), int(m.group(3)))
    return '.'.join(map(str, nums)), nums


def sdk_version() -> str:
    deps = os.path.join(ROOT, '_deps', 'webview2')
    marks = [f for f in sorted(os.listdir(deps)) if f.startswith('.complete-')] if os.path.isdir(deps) else []
    if len(marks) != 1:
        raise RuntimeError('the WebView2 SDK is not unpacked: run python tools/fetch_webview2.py')
    return marks[0][len('.complete-'):]


def rc_path(path: str) -> str:
    """A path as a resource script wants it: forward slashes, quoted."""
    return '"' + os.path.abspath(path).replace('\\', '/') + '"'


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', required=True, help='folder for vitro_app.rc and table.txt')
    args = ap.parse_args()

    dist = os.path.join(ROOT, 'web', 'dist')
    if not os.path.isfile(os.path.join(dist, 'index.html')):
        print(f'make_app_resources: {dist} has no index.html: run `npm run build` in web/ (or use a checkout that has web/dist)', file=sys.stderr)
        return 1
    loader = os.path.join(ROOT, '_deps', 'webview2', 'WebView2Loader.dll')
    notices = os.path.join(ROOT, 'THIRD_PARTY_NOTICES.txt')
    for needed in (loader, notices, os.path.join(ROOT, 'cpp', 'res', 'vitro.ico'), os.path.join(ROOT, 'cpp', 'res', 'vitro.manifest')):
        if not os.path.isfile(needed):
            print(f'make_app_resources: {needed} is missing', file=sys.stderr)
            return 1

    items: list[tuple[int, str, str, str, str]] = []  # id, kind, mime, name, file
    next_id = 100
    for base, _dirs, files in sorted(os.walk(dist)):
        for fn in sorted(files):
            path = os.path.join(base, fn)
            ext = os.path.splitext(fn)[1].lower()
            if ext not in MIME:
                print(f'make_app_resources: {path}: no content type is known for "{ext}"; add it to MIME here and in python/vitro/webserver.py', file=sys.stderr)
                return 1
            items.append((next_id, 'asset', MIME[ext], os.path.relpath(path, dist).replace('\\', '/'), path))
            next_id += 1
    samples = os.path.join(ROOT, 'samples')
    for fn in sorted(os.listdir(samples)):
        if fn.endswith(SAMPLE_SUFFIXES):
            items.append((next_id, 'sample', 'application/octet-stream', fn, os.path.join(samples, fn)))
            next_id += 1
    items.append((next_id, 'loader', 'application/octet-stream', sdk_version(), loader))
    next_id += 1
    items.append((next_id, 'notice', 'text/plain; charset=utf-8', 'THIRD_PARTY_NOTICES.txt', notices))

    os.makedirs(args.out, exist_ok=True)
    table = os.path.join(args.out, 'table.txt')
    with open(table, 'w', encoding='utf-8', newline='\n') as fh:
        for rid, kind, mime, name, _file in items:
            fh.write(f'{rid}\t{kind}\t{mime}\t{name}\n')

    version, nums = project_version()
    lines = [
        '// Generated by tools/make_app_resources.py. Do not edit.',
        f'1 ICON {rc_path(os.path.join(ROOT, "cpp", "res", "vitro.ico"))}',
        f'1 24 {rc_path(os.path.join(ROOT, "cpp", "res", "vitro.manifest"))}',
        '1 VERSIONINFO',
        f' FILEVERSION {nums[0]},{nums[1]},{nums[2]},0',
        f' PRODUCTVERSION {nums[0]},{nums[1]},{nums[2]},0',
        ' FILEOS 0x4L',
        ' FILETYPE 0x1L',
        'BEGIN',
        '  BLOCK "StringFileInfo"',
        '  BEGIN',
        '    BLOCK "040904B0"',
        '    BEGIN',
        '      VALUE "CompanyName", "EldRoot Studios"',
        '      VALUE "FileDescription", "Vitro: a glass-box inspector for PyTorch traces"',
        f'      VALUE "FileVersion", "{version}"',
        '      VALUE "InternalName", "vitro"',
        '      VALUE "LegalCopyright", "Copyright (c) 2026 EldRoot Studios. MIT License."',
        '      VALUE "OriginalFilename", "vitro.exe"',
        '      VALUE "ProductName", "Vitro"',
        f'      VALUE "ProductVersion", "{version}"',
        '    END',
        '  END',
        '  BLOCK "VarFileInfo"',
        '  BEGIN',
        '    VALUE "Translation", 0x409, 1200',
        '  END',
        'END',
        f'1 RCDATA {rc_path(table)}',
    ]
    for rid, _kind, _mime, _name, file in items:
        lines.append(f'{rid} RCDATA {rc_path(file)}')
    with open(os.path.join(args.out, 'vitro_app.rc'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    total = sum(os.path.getsize(f) for *_x, f in items)
    print(f'make_app_resources: {len(items)} items, {total / 1e6:.1f} MB, version {version}', flush=True)
    return 0


if __name__ == '__main__':
    sys.exit(main())

"""Fetches the Microsoft WebView2 SDK that bin/vitro.exe is built against.

The app window is the Edge engine that Windows already has (the "WebView2 runtime"). Building the host needs two
things from Microsoft's SDK package: the C++ header `WebView2.h` and `WebView2Loader.dll`, which finds the installed
engine. This script downloads the pinned package from NuGet once, checks its SHA-256, and unpacks into
`_deps/webview2/`:

    WebView2.h            the interface declarations
    webview2_uuids.hpp    made here: their IIDs in the form MinGW's __uuidof wants (the SDK ships none)
    WebView2Loader.dll    embedded into vitro.exe, so that the program is a single file
    LICENSE.txt, NOTICE.txt

Run by build.sh; safe to run again (it does nothing when `_deps/webview2` is complete).

    python tools/fetch_webview2.py
"""
from __future__ import annotations

import hashlib
import io
import os
import re
import sys
import urllib.request
import zipfile

VERSION = '1.0.4258.31'
SHA256 = '56f7f4b8bf9aee4b8efefbbdd4f67d5f74ebd1b100ed0806da71bf76af481aa9'
URL = f'https://api.nuget.org/v3-flatcontainer/microsoft.web.webview2/{VERSION}/microsoft.web.webview2.{VERSION}.nupkg'

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(ROOT, '_deps', 'webview2')
MARKER = os.path.join(DEST, f'.complete-{VERSION}')
WANTED = {
    'build/native/include/WebView2.h': 'WebView2.h',
    'build/native/x64/WebView2Loader.dll': 'WebView2Loader.dll',
    'LICENSE.txt': 'LICENSE.txt',
    'NOTICE.txt': 'NOTICE.txt',
}


def write(name: str, data: bytes) -> None:
    with open(os.path.join(DEST, name), 'wb') as fh:
        fh.write(data)


def uuid_header(header_text: str) -> str:
    """`__CRT_UUID_DECL` lines for every interface WebView2.h declares with MIDL_INTERFACE("<guid>")."""
    found = re.findall(r'MIDL_INTERFACE\("([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})"\)\s*(\w+)', header_text)
    if len(found) < 100:
        raise RuntimeError(f'WebView2.h: found only {len(found)} interfaces; its layout has changed and this script must be updated')
    lines = ['// Generated by tools/fetch_webview2.py from WebView2.h. Do not edit.', '#pragma once', '#include <windows.h>', '']
    for guid, name in found:
        a, b, c, d, e = guid.split('-')
        tail = ', '.join(f'0x{x}' for x in (d[:2], d[2:], e[0:2], e[2:4], e[4:6], e[6:8], e[8:10], e[10:12]))
        lines.append(f'__CRT_UUID_DECL({name}, 0x{a}, 0x{b}, 0x{c}, {tail})')
    return '\n'.join(lines) + '\n'


def main() -> int:
    if os.path.isfile(MARKER):
        return 0
    print(f'fetch_webview2: downloading Microsoft.Web.WebView2 {VERSION} from NuGet ...', flush=True)
    try:
        data = urllib.request.urlopen(URL, timeout=180).read()
    except OSError as e:
        print(f'fetch_webview2: cannot download {URL}: {e}', file=sys.stderr)
        return 1
    got = hashlib.sha256(data).hexdigest()
    if got != SHA256:
        print(f'fetch_webview2: the package does not match the pinned SHA-256 (got {got}, expected {SHA256}); not using it', file=sys.stderr)
        return 1
    os.makedirs(DEST, exist_ok=True)
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        for member, name in WANTED.items():
            write(name, z.read(member))
    with open(os.path.join(DEST, 'WebView2.h'), encoding='utf-8', errors='replace') as fh:
        write('webview2_uuids.hpp', uuid_header(fh.read()).encode('utf-8').replace(b'\r\n', b'\n'))
    write(os.path.basename(MARKER), VERSION.encode('ascii'))
    print(f'fetch_webview2: ready in {DEST}', flush=True)
    return 0


if __name__ == '__main__':
    sys.exit(main())
